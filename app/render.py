"""简报渲染：同一份数据分别产出 Markdown（归档）与 HTML（邮件）。

关于内容边界的原则（对应需求 7"必须基于原文、区分Authors结论与分析"）：
  * Focus / Contribution / Findings / Abstract 四段**逐字来自 BIS 官方Abstract**，
    是Authors本人的表述，渲染时全部标注为「BIS 原文」。
  * Priority分数与Ranking rationale是**本系统按 JEL/Keywords规则自动计算的**，
    不是Authors观点，单独标注为「System score」。
  * 当前为纯抓取模式（未接大模型），因此不生成"关键证据/局限性/实际意义"
    这三项需要通读全文才能得出的内容，页面上如实说明缺口，而不是编造。
"""
from __future__ import annotations

import html
import re
from datetime import datetime
from typing import Any, Sequence
from zoneinfo import ZoneInfo

from . import config, scoring

COVERAGE_NOTE = (
    "This digest reproduces available sections from BIS abstracts, attributed to BIS. "
    "Detailed evidence, limitations and implications require reading the full paper and "
    "are not generated by the automatic collection process."
)
RANKING_NOTE = (
    "Priority is calculated by the system, not the authors: JEL codes and keywords are "
    "weighted for fixed income, FX and monetary policy, with adjustments for abstract "
    "structure and length. Weights are configurable in app/config.py."
)
SUMMARY_SECTIONS = [
    ("research_question", "Research question"), ("core_findings", "Core findings"),
    ("method_and_data", "Method and data"), ("key_evidence", "Key evidence"),
    ("contribution", "Contribution"), ("limitations", "Limitations"),
    ("implications", "Implications"),
]
SECTION_MAP = [
    ("focus", "Focus", "BIS original: Focus"),
    ("findings", "Findings", "BIS original: Findings"),
    ("contribution", "Contribution", "BIS original: Contribution"),
    ("abstract", "Abstract", "BIS original: Abstract"),
]


def now_local() -> datetime:
    try:
        return datetime.now(ZoneInfo(config.TIMEZONE))
    except Exception:
        return datetime.now()


def stamp() -> str:
    return now_local().strftime("%Y-%m-%d %H:%M") + f" ({config.TIMEZONE})"


def _authors(paper: dict[str, Any]) -> str:
    names = paper.get("authors") or []
    return ", ".join(names) if names else "—"


def _pdf_note(paper: dict[str, Any]) -> str:
    bits = []
    if paper.get("pdf_pages"):
        bits.append(f"{paper['pdf_pages']} pages")
    if paper.get("pdf_size_kb"):
        bits.append(f"{paper['pdf_size_kb']} KB")
    return ", ".join(bits)


def digest_title(count: int) -> str:
    if count == 0:
        return "BIS Working Papers: no new papers found"
    return f"BIS Working Papers: {count} new {'paper' if count == 1 else 'papers'} found"


# ---------------------------------------------------------------- Markdown
def to_markdown(papers: Sequence[dict[str, Any]]) -> str:
    lines: list[str] = []
    add = lines.append

    add(f"# {digest_title(len(papers))}")
    add("")
    add(f"> Checked：{stamp()}  ")
    add(f"> Source：<https://www.bis.org/publications/working-paper>")
    add("")

    if not papers:
        add("No new papers found in this check.")
        add("")
        return "\n".join(lines)

    # ---- 汇总表 ----
    if len(papers) > 1:
        add("## Summary (ranked by reading priority)")
        add("")
        add("| # | Priority | Number | Title | Authors | Publication date | Length | Ranking rationale |")
        add("|---|---|---|---|---|---|---|---|")
        for i, p in enumerate(papers, 1):
            score = int(p.get("relevance") or 0)
            add(
                f"| {i} | {scoring.tier(score)}（{score}） | No {p['series']} | "
                f"[{p['title']}]({p['abstract_url']}) | {_authors(p)} | "
                f"{p['pub_date']} | {_pdf_note(p) or '—'} | "
                f"{p.get('relevance_why') or '—'} |"
            )
        add("")
        add(f"> {RANKING_NOTE}")
        add("")

    add(f"> {COVERAGE_NOTE}")
    add("")
    add("---")
    add("")

    # ---- 逐篇 ----
    for i, p in enumerate(papers, 1):
        add(f"## {i}. {p['title']}")
        add("")
        add(f"- **Number**：BIS Working Papers No {p['series']}")
        add(f"- **Authors**：{_authors(p)}")
        add(f"- **Publication date**：{p['pub_date']}")
        add(f"- **Abstract**：<{p['abstract_url']}>")
        pdf_note = _pdf_note(p)
        if p.get("pdf_url"):
            add(f"- **PDF**: <{p['pdf_url']}>" + (f" ({pdf_note})" if pdf_note else ""))
        if p.get("jel_codes"):
            add(f"- **JEL**：{', '.join(p['jel_codes'])}")
        if p.get("keywords"):
            add(f"- **Keywords**：{', '.join(p['keywords'])}")
        score = int(p.get("relevance") or 0)
        add(
            f"- **System score**：{scoring.tier(score)}（{score}）— "
            f"{p.get('relevance_why') or '—'} *(calculated by the system, not the authors)*"
        )
        add("")

        has_any = False
        for key, zh, provenance in SECTION_MAP:
            text = (p.get(key) or "").strip()
            if not text:
                continue
            has_any = True
            add(f"### {zh}")
            add(f"*<{provenance}>*")
            add("")
            add(text)
            add("")

        if not has_any:
            add("> No structured abstract is available; see the original PDF.")
            add("")

        add("### Key Takeaway")
        add("*<BIS original findings; no additional interpretation>*")
        add("")
        add((p.get("findings") or p.get("abstract") or "—").strip())
        add("")
        add("---")
        add("")

    return "\n".join(lines)


# ---------------------------------------------------------------- 中文深度总结
# 紧跟数字的星号是计量显著性标记，不是 Markdown 语法
_SIG_STARS_RE = re.compile(r"(?<=[0-9])(\*{1,3})")


def _protect_stars(text: str) -> str:
    """转义显著性星号，避免被 Markdown 渲染器当成加粗吃掉。

    页面渲染靠 app/main.py 的 _BOLD_RE 区分两种星号，但导出的 .md 走的是
    另一条路：原样输出的话，`-0.037**` 后面只要再出现一个 `**`，
    CommonMark 就会把中间整段配对成加粗，两处星号双双消失 ——
    显著性等级没了，读者还看不出少了东西。

    只转义紧跟数字的那些；成对包裹词组的 `**加粗**` 保持原样。
    """
    return _SIG_STARS_RE.sub(lambda m: "\\*" * len(m.group(1)), text or "")


def summary_to_markdown(
    zh: dict[str, Any], paper: dict[str, Any] | None = None
) -> str:
    """把一份中文深度总结渲染成可直接粘进论文草稿的 Markdown。"""
    lines: list[str] = []
    add = lines.append
    series = zh.get("series", "")

    add(f"## No {series}　{zh.get('title_zh') or (paper or {}).get('title', '')}")
    add("")
    if paper:
        add(f"*{paper.get('title', '')}*")
        add("")
    if zh.get("citation"):
        add(f"> **引用**：{zh['citation']}")
        add("")

    caveats = (zh.get("review") or {}).get("caveats") or []
    if caveats:
        add("> **引用前请先核对这几处**")
        for caveat in caveats:
            add(f"> - {caveat}")
        add("")
    meta: list[str] = []
    if paper:
        if paper.get("authors"):
            meta.append("Authors：" + ", ".join(paper["authors"]))
        if paper.get("pub_date"):
            meta.append(f"发布：{paper['pub_date']}")
        if paper.get("pdf_pages"):
            meta.append(f"{paper['pdf_pages']} pages")
        meta.append(f"[Abstract]({paper.get('abstract_url', '')})")
        if paper.get("pdf_url"):
            meta.append(f"[PDF]({paper['pdf_url']})")
    if meta:
        add("　·　".join(meta))
        add("")

    for key, label in SUMMARY_SECTIONS:
        value = zh.get(key)
        if not value:
            continue
        add(f"### {label}")
        add("")
        if key == "core_findings":
            for i, item in enumerate(value, 1):
                add(f"{i}. {_protect_stars(item)}")
            add("")
        elif key == "key_evidence":
            for item in value:
                anchor = item.get("anchor", "")
                number = item.get("number", "")
                head = f"**{anchor}**" + (f"　`{number}`" if number else "")
                add(f"- {head}")
                add(f"  {_protect_stars(item.get('detail', ''))}")
            add("")
        else:
            add(_protect_stars(str(value)))
            add("")

    if zh.get("key_takeaway"):
        add("### Key Takeaway")
        add("")
        add(_protect_stars(zh["key_takeaway"]))
        add("")

    thesis = zh.get("thesis") or {}
    if thesis:
        add("### 写作参考")
        add("")
        if thesis.get("data_sources"):
            add(f"- **数据来源与可得性**：{thesis['data_sources']}")
        if thesis.get("replicability"):
            add(f"- **在中国市场复现**：{thesis['replicability']}")
        if thesis.get("related_series"):
            related = "、".join(f"No {s}" for s in thesis["related_series"])
            add(f"- **相关论文**：{related}")
        if thesis.get("research_gaps"):
            add("- **可延续的研究方向**：")
            for gap in thesis["research_gaps"]:
                add(f"  - {gap}")
        add("")

    review = zh.get("review") or {}
    if review.get("status") and review["status"] != "passed":
        add(
            f"> ⚠️ **{review.get('status')}**：这份总结尚未通过独立质检，"
            "引用前务必对照 PDF 原文核实。"
        )
        add("")
    add(
        f"*总结方式：{zh.get('generated_by', '全文精读')}"
        f"（{zh.get('generated_at', '')}）。"
        "Core findings and evidence describe the authors’ findings; "
        "limitations and implications include the note writer’s judgment. "
        "每条证据均标注表号，引用前建议对回原文。*"
    )
    add("")
    return "\n".join(lines)


# ---------------------------------------------------------------- HTML 邮件
def _h(text: Any) -> str:
    return html.escape(str(text if text is not None else ""))


