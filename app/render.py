_TIER_CLASS = {"High": "b-hi", "Medium": "b-mid", "Low": "b-lo"}


def to_html(papers: Sequence[dict[str, Any]]) -> str:
    out: list[str] = []
    add = out.append

    add(f"<!doctype html><html><head><meta charset='utf-8'><style>{_CSS}</style>"
        f"</head><body><div class='wrap'>")
    add("<div class='card'>")
    add(f"<h1>{_h(digest_title(len(papers)))}</h1>")
    add(f"<p class='meta'>Checked：{_h(stamp())}</p>")
    add("<p class='meta'>Source：<a href='https://www.bis.org/publications/working-paper'>"
        "BIS Working Papers</a></p>")
    if config.PUBLIC_URL:
        add(f"<p class='meta'>Dashboard：<a href='{_h(config.PUBLIC_URL)}'>"
            f"{_h(config.PUBLIC_URL)}</a></p>")
    add("</div>")

    if not papers:
        add("<div class='card'><p>No new papers found in this check.</p></div>")
        add("</div></body></html>")
        return "".join(out)

    if len(papers) > 1:
        add("<div class='card'><h2>Summary (ranked by reading priority)</h2><table>")
        add("<tr><th>#</th><th>Priority</th><th>Number</th><th>Title</th><th>Authors</th>"
            "<th>Publication date</th><th>Ranking rationale</th></tr>")
        for i, p in enumerate(papers, 1):
            score = int(p.get("relevance") or 0)
            t = scoring.tier(score)
            add(
                f"<tr><td>{i}</td>"
                f"<td><span class='badge {_TIER_CLASS[t]}'>{t} {score}</span></td>"
                f"<td>No {_h(p['series'])}</td>"
                f"<td><a href='{_h(p['abstract_url'])}'>{_h(p['title'])}</a></td>"
                f"<td>{_h(_authors(p))}</td><td>{_h(p['pub_date'])}</td>"
                f"<td>{_h(p.get('relevance_why') or '—')}</td></tr>"
            )
        add("</table>")
        add(f"<div class='note'>{_h(RANKING_NOTE)}</div></div>")

    add(f"<div class='card'><div class='note'>{_h(COVERAGE_NOTE)}</div></div>")

    for i, p in enumerate(papers, 1):
        add("<div class='card'>")
        add(f"<h2>{i}. {_h(p['title'])}</h2>")
        add("<ul>")
        add(f"<li><b>Number</b>：BIS Working Papers No {_h(p['series'])}</li>")
        add(f"<li><b>Authors</b>：{_h(_authors(p))}</li>")
        add(f"<li><b>Publication date</b>：{_h(p['pub_date'])}</li>")
        add(f"<li><b>Abstract</b>：<a href='{_h(p['abstract_url'])}'>{_h(p['abstract_url'])}</a></li>")
        pdf_note = _pdf_note(p)
        if p.get("pdf_url"):
            add(f"<li><b>PDF</b>: <a href='{_h(p['pdf_url'])}'>{_h(p['pdf_url'])}</a>"
                + (f" ({_h(pdf_note)})" if pdf_note else "") + "</li>")
        if p.get("jel_codes"):
            add(f"<li><b>JEL</b>：{_h(', '.join(p['jel_codes']))}</li>")
        if p.get("keywords"):
            add(f"<li><b>Keywords</b>：{_h(', '.join(p['keywords']))}</li>")
        score = int(p.get("relevance") or 0)
        add(f"<li><b>System score</b>：{scoring.tier(score)}（{score}）—"
            f" {_h(p.get('relevance_why') or '—')}"
            f" <i>(calculated by the system, not the authors)</i></li>")
        add("</ul>")

        has_any = False
        for key, zh, provenance in SECTION_MAP:
            text = (p.get(key) or "").strip()
            if not text:
                continue
            has_any = True
            add(f"<h3>{_h(zh)}</h3><p class='prov'>{_h(provenance)}</p><p>{_h(text)}</p>")
        if not has_any:
            add("<p class='note'>No structured abstract is available; see the original PDF.</p>")

        add("<h3>Key Takeaway</h3><p class='prov'>BIS original findings; no additional interpretation</p>")
        add(f"<p>{_h((p.get('findings') or p.get('abstract') or '—').strip())}</p>")
        add("</div>")

    add("<div class='foot'>bis-wpapers-monitor · Automatically generated</div>")
    add("</div></body></html>")
    return "".join(out)
